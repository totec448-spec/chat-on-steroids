//! The `tools/list` elements and static instruction blocks recorded from the TypeScript app.
//!
//! `declarations.json` is written by `scripts/golden/extract-declarations.mjs` from the golden
//! corpus. Each surface's list is in listing order, and each element keeps the key order the
//! TypeScript server sent, so rendering a template reproduces its bytes. `{{roots}}` is the only
//! placeholder: the approved roots named in `read`'s path description.

use std::sync::LazyLock;

use serde::Deserialize;
use serde_json::Value;

use crate::SurfaceId;

const ROOTS: &str = "{{roots}}";

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
pub(crate) struct Instructions {
    /// The adapted Codex collaboration instructions that open Core's instructions.
    pub coding: String,
    pub code_mode: String,
    pub browser: String,
    pub windows_desktop: String,
}

#[derive(Deserialize)]
struct Surfaces {
    core: Vec<Value>,
    desktop: Vec<Value>,
    plugins: Vec<Value>,
}

#[derive(Deserialize)]
struct File {
    instructions: Instructions,
    surfaces: Surfaces,
}

pub(crate) struct Declarations {
    pub instructions: Instructions,
    surfaces: Surfaces,
}

/// A recorded element and its position in the surface's listing order.
pub(crate) struct Declaration<'a> {
    pub position: usize,
    template: &'a Value,
}

impl Declaration<'_> {
    pub fn input_schema(&self) -> &Value {
        &self.template["inputSchema"]
    }

    /// The listed description with this call's roots filled in.
    pub fn description(&self, roots: &str) -> String {
        match fill(&self.template["description"], roots) {
            Value::String(text) => text,
            _ => String::new(),
        }
    }

    /// The `tools/list` element with this call's roots filled in.
    pub fn render(&self, roots: &str) -> Value {
        fill(self.template, roots)
    }
}

pub(crate) static DECLARATIONS: LazyLock<Declarations> = LazyLock::new(|| {
    let file: File = serde_json::from_str(include_str!("../declarations.json"))
        .expect("declarations.json is generated by extract-declarations.mjs and parsed by a test");
    Declarations {
        instructions: file.instructions,
        surfaces: file.surfaces,
    }
});

impl Declarations {
    fn of(&self, surface: SurfaceId) -> &[Value] {
        match surface {
            SurfaceId::Core => &self.surfaces.core,
            SurfaceId::Desktop => &self.surfaces.desktop,
            SurfaceId::Plugins => &self.surfaces.plugins,
        }
    }

    pub fn find(&self, surface: SurfaceId, name: &str) -> Option<Declaration<'_>> {
        self.of(surface)
            .iter()
            .enumerate()
            .find(|(_, template)| template["name"] == name)
            .map(|(position, template)| Declaration { position, template })
    }
}

fn fill(template: &Value, roots: &str) -> Value {
    match template {
        Value::String(text) if text.contains(ROOTS) => Value::String(text.replace(ROOTS, roots)),
        Value::Array(items) => Value::Array(items.iter().map(|item| fill(item, roots)).collect()),
        Value::Object(fields) => Value::Object(
            fields
                .iter()
                .map(|(key, value)| (key.clone(), fill(value, roots)))
                .collect(),
        ),
        other => other.clone(),
    }
}
